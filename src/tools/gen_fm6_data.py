"""firmware/gen/lgs_fm6_data.h: the msfa tables of the FM6 core (clipper-smk/tools/gen_tables.py, FM6_*) and Clipper's own eight
FM6 voices (clipper-smk/tools/gen_fm6_patches.py: authored settings, no ROM data), made on a scratch copy of clipper-smk."""
import pathlib, re, shutil, subprocess, sys, tempfile
root = pathlib.Path(__file__).resolve().parent.parent
clip = root.parent / "clipper-smk"
tmp = pathlib.Path(tempfile.mkdtemp(prefix="lgs-fm6-"))
shutil.copytree(clip, tmp / "c", ignore=shutil.ignore_patterns(".git", "build"))
subprocess.run([sys.executable, str(tmp / "c" / "tools" / "gen_tables.py"), str(tmp / "t.h")], check=True)
subprocess.run([sys.executable, str(tmp / "c" / "tools" / "gen_fm6_patches.py"), str(tmp / "p.h")], check=True)
t = (tmp / "t.h").read_text()
out = ["/* GENERATED by tools/gen_fm6_data.py (msfa tables: Apache-2.0, Google Inc. / Pascal Gauthier; Felucca port and patches: Copyright (C) 2026 Leo Kuroshita, Hugelton Instruments) - do not edit */"]
out += re.findall(r"^#define FM6_.*$", t, re.M)
for name in ("FM6_EXP2", "FM6_LFO_DELTA", "FM6_DETUNE", "FM6_FINE"):
    m = re.search(r"static const \w+ %s\[\d+\] = \{.*?\n\};" % name, t, re.S)
    assert m, name
    out.append(m.group(0))
p = (tmp / "p.h").read_text()
out.append(p.replace("#pragma once", "").replace("#include <stdint.h>", ""))
(root / "firmware" / "gen" / "lgs_fm6_data.h").write_text("\n".join(out) + "\n")
shutil.rmtree(tmp)
print("wrote lgs_fm6_data.h")
