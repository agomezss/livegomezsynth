"""Tables the Clipper engines need, for their 32-sample control block at 44.1 kHz (as clipper-smk/tools/gen_tables.py):
SINE (1025 points, Q15) and ENV_EXP (per-block exponential coefficient for 1 ms .. 10 s)."""
import math, pathlib
FS, CTL = 44100, 32
root = pathlib.Path(__file__).resolve().parent.parent
def arr(name, ctype, vals, per=12):
    out = ["static const %s %s[%d] = {" % (ctype, name, len(vals))]
    for i in range(0, len(vals), per):
        out.append("    " + ", ".join(str(v) for v in vals[i:i + per]) + ",")
    out.append("};")
    return out
ms = [1.0 * (10000 ** (v / 127)) for v in range(128)]
exp_k = []
for m in ms:
    tau = m / 1000 / 4.6
    exp_k.append(max(1, min(65535, int(65536 * (1 - math.exp(-CTL / (tau * FS)))))))
L = ["/* GENERATED by tools/gen_engine_tables.py - do not edit */", "#define E32_CTL 32u"]
L += arr("E32_SINE", "int16_t", [int(round(32767 * math.sin(2 * math.pi * i / 1024))) for i in range(1025)])
L += arr("E32_ENV_EXP", "uint16_t", exp_k)
L += arr("E32_POW2", "uint32_t", [int(65536 * 2 ** (i / 192)) for i in range(192)], 8)   # 2^(i/192), Q16: the SP engine's pitch ratios
(root / "firmware" / "gen" / "lgs_engine_tables.h").write_text("\n".join(L) + "\n")
print("wrote lgs_engine_tables.h")
