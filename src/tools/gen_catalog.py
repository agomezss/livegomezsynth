"""catalog/catalog.json -> firmware/src/lgs_catalog_data.h. The ids are the numbers shown on the screen: sequential in category
order (D-68). A patch keeps its id when it is renamed or moves; a removed id is retired. catalog/idmap.json maps the ids of the
first numbering (images written up to 0.1.12) to the second, idmap1.json the second to the current one (0 = removed): the firmware
applies the composed table once to an older image."""
import json, re, sys, pathlib, collections
root = pathlib.Path(__file__).resolve().parent.parent
cat = json.load(open(root / "catalog" / "catalog.json"))
cats, ps = cat["categories"], cat["patches"]
ids = [p["id"] for p in ps]
assert len(set(ids)) == len(ids), "duplicate patch id"
assert cats[0] == "Favorites", "category 1 is the user's favorites"
for p in ps:
    assert 2 <= p["cat"] <= len(cats), p
    assert 0 < p["id"] < 1000, p
    assert len(p["name"]) <= 16, p
assert max(collections.Counter(p["cat"] for p in ps).values()) <= 255, "cat_n is a uint8"
ps.sort(key=lambda p: (p["cat"], p["id"]))   # a category is one contiguous run (cat_init in lgs_model.h)
trims = json.load(open(root / "catalog" / "trims.json")) if (root / "catalog" / "trims.json").exists() else {}   # level match by name, written by tests/catalog_health.mjs --trim
ENG = {"syn": 0, "drm": 2, "fm2": 3, "org": 4, "sp": 5, "fm6": 6, "voc": 7}   # = OBV_ANALOG / OBV_DRUMS (obv_engine_patch.h)
out = ["/* GENERATED by tools/gen_catalog.py from catalog/catalog.json - do not edit */",
       "typedef struct { uint16_t id; uint8_t cat, engine, data, trim; char name[17]; } lgs_patch_t;",
       "#define LGS_NPATCH %du" % len(ps),
       "#define LGS_NCAT %du" % len(cats),
       "static const char *const LGS_CAT_NAME[LGS_NCAT + 1] = {\"\", %s};" % ", ".join('"%s"' % c for c in cats),
       "static const lgs_patch_t LGS_PATCH[LGS_NPATCH] = {"]
for p in ps:
    out.append('    {%d, %d, %d, %d, %d, "%s"},' % (p["id"], p["cat"], ENG[p["engine"]], p["factory"], trims.get(p["name"], 64), p["name"]))
out.append("};")
# catalog/idmap.json: generation 0 -> 1; catalog/idmapN.json: generation N -> N+1 (0 = removed). Each older generation gets one table
# composed up to the current ids; the firmware applies it once to an older image (lgs_store.h)
gens = int(re.search(r"#define LGS_ID_GEN (\d+)u", (root / "firmware" / "src" / "lgs_model.h").read_text()).group(1))
steps = [json.load(open(root / "catalog" / ("idmap.json" if n == 0 else "idmap%d.json" % n))) for n in range(gens)]
steps = [{int(k): v for k, v in m.items()} for m in steps]
tabs = []
for g in range(gens):
    cur = dict(steps[g])
    for h in range(g + 1, gens):
        cur = {k: (steps[h].get(v, 0) if v else 0) for k, v in cur.items()}
    assert all(v == 0 or v in ids for v in cur.values()), "idmap points at an id that is not in the catalog"
    tabs.append(cur)
out.append("/* ids of generation g (index) -> the current id, 0 = removed (db generation g, lgs_store.h) */")
out.append("#define LGS_IDMAP_GENS %du" % gens)
for g, t in enumerate(tabs):
    n = max(t) + 1
    out.append("#define LGS_IDMAP%d_N %du" % (g, n))
    out.append("static const uint16_t LGS_IDMAP%d[LGS_IDMAP%d_N] = {%s};" % (g, g, ", ".join(str(t.get(i, 0)) for i in range(n))))
out.append("static const uint16_t *const LGS_IDMAP[LGS_IDMAP_GENS] = {%s};" % ", ".join("LGS_IDMAP%d" % g for g in range(gens)))
out.append("static const uint16_t LGS_IDMAP_N[LGS_IDMAP_GENS] = {%s};" % ", ".join("LGS_IDMAP%d_N" % g for g in range(gens)))
dst = root / "firmware" / "src" / "lgs_catalog_data.h"
dst.write_text("\n".join(out) + "\n")
print("wrote", dst, len(ps), "patches")
