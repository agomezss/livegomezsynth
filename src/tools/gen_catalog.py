"""catalog/catalog.json -> firmware/src/lgs_catalog_data.h (IDs are immutable and never reused: a patch keeps its id when it
moves to another category or is renamed; a removed id is retired; D-66)."""
import json, sys, pathlib, collections
root = pathlib.Path(__file__).resolve().parent.parent
cat = json.load(open(root / "catalog" / "catalog.json"))
cats, ps = cat["categories"], cat["patches"]
ids = [p["id"] for p in ps]
assert len(set(ids)) == len(ids), "duplicate patch id"
assert cats[0] == "Favorites", "category 1 is the user's favorites"
for p in ps:
    assert 2 <= p["cat"] <= len(cats), p
    assert 0 < p["id"] < 1000, p
    assert len(p["name"]) <= 16, p
assert max(collections.Counter(p["cat"] for p in ps).values()) <= 255, "cat_n is a uint8"
ps.sort(key=lambda p: (p["cat"], p["id"]))   # a category is one contiguous run (cat_init in lgs_model.h)
trims = json.load(open(root / "catalog" / "trims.json")) if (root / "catalog" / "trims.json").exists() else {}   # level match by name, written by tests/catalog_health.mjs --trim
ENG = {"syn": 0, "drm": 2, "fm2": 3, "org": 4, "sp": 5, "fm6": 6, "voc": 7}   # = OBV_ANALOG / OBV_DRUMS (obv_engine_patch.h)
out = ["/* GENERATED by tools/gen_catalog.py from catalog/catalog.json - do not edit */",
       "typedef struct { uint16_t id; uint8_t cat, engine, data, trim; char name[17]; } lgs_patch_t;",
       "#define LGS_NPATCH %du" % len(ps),
       "#define LGS_NCAT %du" % len(cats),
       "static const char *const LGS_CAT_NAME[LGS_NCAT + 1] = {\"\", %s};" % ", ".join('"%s"' % c for c in cats),
       "static const lgs_patch_t LGS_PATCH[LGS_NPATCH] = {"]
for p in ps:
    out.append('    {%d, %d, %d, %d, %d, "%s"},' % (p["id"], p["cat"], ENG[p["engine"]], p["factory"], trims.get(p["name"], 64), p["name"]))
out.append("};")
dst = root / "firmware" / "src" / "lgs_catalog_data.h"
dst.write_text("\n".join(out) + "\n")
print("wrote", dst, len(ps), "patches")
