"""Builds firmware/gen/lgs_samples.h: the sample sets of the SP engine, from Clipper's own generator (clipper-smk/tools/
gen_samples.py, IMA ADPCM) run on a scratch copy (the reference repository is never touched). Needs numpy.
Sets: four CC0 sets (PIANO, HORNS, STRGS, FLUTE; assets/samples-cc0, attribution there) and the four sets Clipper
synthesises itself (VOX, GLASS, PAD, AIR; tools/gen_clipper_sets.py), concatenated into one table.
  python3 tools/gen_lgs_samples.py [--venv ~/lgs-scratch/venv/bin/python]"""
import pathlib, re, shutil, subprocess, sys, tempfile
root = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(root / "tools"))
import famous_defs as D
clip = root.parent / "clipper-smk"
py = sys.executable
if "--venv" in sys.argv:
    py = sys.argv[sys.argv.index("--venv") + 1]
tmp = pathlib.Path(tempfile.mkdtemp(prefix="lgs-samples-"))
shutil.copytree(clip, tmp / "c", ignore=shutil.ignore_patterns(".git", "build"))
g = tmp / "c" / "tools" / "gen_samples.py"
s = g.read_text()
a = s.index("CC0_SETS = ["); b = s.index("MEASURED_TUNING")
s = s[:a] + 'CC0_SETS = [("PIANO", "piano"), ("HORNS", "oneshot"), ("STRGS", "oneshot"), ("FLUTE", "sus")]\n' + s[b:]
s = s.replace("    b.gm_kit(have_cc0)", "    pass")
g.write_text(s)
(tmp / "c" / "build").mkdir()
raw = tmp / "raw.h"
subprocess.run([py, str(g), str(raw)], check=True, cwd=tmp / "c")
text = raw.read_text()
i, j = text.index("#if !CLIPPER_SYNTH"), text.index("#else")
A, B = text[i:j], text[j:text.index("#endif", j)]

def parse(blk):
    d = re.search(r"SMP_DATA\[(\d+)\] = \{(.*?)\};", blk, re.S)
    n = int(d.group(1)); data = [int(x) for x in re.findall(r"\d+", d.group(2))]
    assert len(data) == n
    zones = [tuple(int(x) for x in r) for r in re.findall(r"\{(\d+), (\d+), (\d+), (\d+), (\d+), (-?\d+), (-?\d+), (\d+), (\d+), (\d+), (\d+)\}",
             blk[blk.index("SMP_ZONES"):blk.index("SMP_SETS")])]
    sets = re.findall(r'\{"(\w+)", (\d+), (\d+)\}', blk[blk.index("SMP_SETS"):blk.index("SMP_NSETS")])
    pres = []
    for m in re.finditer(r'\{"([^"]+)", \{([^}]*)\}, \{([^}]*)\}, (-?\d+), (\d+), FX\(([^)]*)\)', blk[blk.index("SMP_PRESET_TABLE"):]):
        pres.append((m.group(1), [int(x) for x in m.group(2).split(",")], [int(x) for x in m.group(3).split(",")], int(m.group(4)), int(m.group(5)), [int(x) for x in m.group(6).split(",")]))
    return data, zones, [(n, int(z0), int(nz)) for n, z0, nz in sets], pres
dA, zA, sA, pA = parse(A)
dB, zB, sB, pB = parse(B)
data = dA + dB
zones = zA + [(o + len(dA),) + z[1:] for z in zB for o in [z[0]]]
sets = sA + [(n, z0 + len(zA), nz) for n, z0, nz in sB]
pres = pA + [(n, [e[0] + len(sA)] + e[1:], env, f, mono, fx) for n, e, env, f, mono, fx in pB]
# our own variations on the sets (set index, TUNE, BITS, LOOP, CUT, -, DRV, -), envelope A D S R, sends DIST CHORUS DELAY REVERB
names = [x[0] for x in sets]
def ex(name, st, e, env, mono, fx): return (name, [names.index(st)] + e, env, 0, mono, fx)
pres += [ex("STRING PAD", "STRGS", [0, 0, 1, 118, 0, 0, 0], [40, 100, 127, 70], 0, [0, 24, 10, 40]),
         ex("SOFT PIANO", "PIANO", [0, 0, 1, 70, 0, 0, 0], [0, 110, 0, 70], 0, [0, 10, 6, 30]),
         ex("BRIGHT PIANO", "PIANO", [0, 0, 1, 127, 0, 12, 0], [0, 100, 0, 50], 0, [0, 6, 4, 18]),
         ex("WARM HORNS", "HORNS", [0, 0, 1, 90, 0, 0, 0], [14, 100, 127, 34], 0, [0, 12, 8, 26]),
         ex("FLUTE PAD", "FLUTE", [0, 0, 1, 110, 0, 0, 0], [30, 90, 127, 70], 0, [0, 20, 20, 40]),
         ex("VOICE PAD", "VOX", [0, 0, 1, 112, 0, 0, 0], [60, 100, 127, 90], 0, [0, 30, 16, 56]),
         ex("CHOIR SWELL", "VOX", [0, 0, 1, 100, 0, 0, 0], [80, 100, 127, 100], 0, [0, 40, 14, 62]),
         ex("GLASS CHOIR", "GLASS", [0, 0, 1, 110, 0, 0, 0], [70, 100, 127, 100], 0, [0, 36, 18, 64]),
         ex("AIR CHOIR", "AIR", [0, 0, 1, 105, 0, 0, 0], [60, 100, 127, 100], 0, [0, 34, 16, 60]),
         ex("SOFT FLUTE", "FLUTE", [0, 0, 1, 92, 0, 0, 0], [22, 90, 127, 55], 0, [0, 14, 18, 34]),
         ex("BREATH", "AIR", [0, 0, 1, 118, 0, 10, 0], [10, 90, 127, 60], 1, [0, 10, 22, 40]),
         ex("CHOIR AAHS", "VOX", [0, 0, 1, 108, 0, 0, 0], [40, 100, 127, 90], 0, [0, 40, 14, 56]),
         ex("PAN FLUTE", "FLUTE", [0, 0, 1, 80, 0, 0, 0], [15, 90, 127, 45], 0, [0, 0, 16, 36])]
for n, st, cut, drv, _bits, env, mono, fx in D.SP:      # ICONIC: set, loop on, CUT, DRV
    pres.append((n, [names.index(st), 0, 0, 1, cut, 0, drv, 0], env, 0, mono, list(fx)))
L = ["/* GENERATED by tools/gen_lgs_samples.py (Clipper's gen_samples.py: Copyright (C) 2026 Leo Kuroshita, Hugelton Instruments, GPL-3.0; samples CC0, see ATTRIBUTION in clipper-smk/assets/samples-cc0) - do not edit */",
     "static const uint8_t SMP_DATA[%d] = {" % len(data)]
for k in range(0, len(data), 24):
    L.append("    " + ", ".join(str(x) for x in data[k:k + 24]) + ",")
L.append("};")
L.append("static const smp_zone_t SMP_ZONES[] = {")
for z in zones: L.append("    {%s}," % ", ".join(str(x) for x in z))
L.append("};")
L.append("static const smp_set_t SMP_SETS[] = {")
for n, z0, nz in sets: L.append('    {"%s", %d, %d},' % (n, z0, nz))
L.append("};")
L.append("#define SMP_NSETS %d" % len(sets))
L.append("static const lgs_preset_t SMP_PRESET_TABLE[] = {")
for n, e, env, f, mono, fx in pres:
    if n == D.SP[0][0]: L.append("    /* ICONIC (tools/famous_defs.py) */")
    L.append('    {"%s", {%s}, {%s}, %d, %d, FX(%s)},' % (n, ", ".join(map(str, e)), ", ".join(map(str, env)), f, mono, ", ".join(map(str, fx))))
L.append("};")
(root / "firmware" / "gen" / "lgs_samples.h").write_text("\n".join(L) + "\n")
print("sets:", [x[0] for x in sets], "bytes", len(data), "presets", [p[0] for p in pres])
shutil.rmtree(tmp)
