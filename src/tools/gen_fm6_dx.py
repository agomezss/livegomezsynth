"""firmware/gen/lgs_fm6_dx.h: the 128 six-operator voices of the SMK-37 open SDK (smk37_open/app/factory_dx7.inc), as the 128-byte
packed records the FM6 engine unpacks (fm6_unpack). Needs smk37_open next to src/ (D-69)."""
import pathlib, re
root = pathlib.Path(__file__).resolve().parent.parent
inc = root.parent / "smk37_open" / "app" / "factory_dx7.inc"
s = re.sub(r"/\*.*?\*/", "", inc.read_text(), flags=re.S)
b = [int(x, 16) for x in re.findall(r"0x([0-9a-fA-F]{2})", s)]
assert len(b) == 128 * 128, len(b)
out = ["/* GENERATED by tools/gen_fm6_dx.py - do not edit.",
       " * Voice data: smk37_open/app/factory_dx7.inc, extracted by M-VAVE from the FM-1 recovery resource (upstream notice: Apache-2.0;",
       " * see THIRD_PARTY.md of smk37_open and DOCs/00-decisions.md D-69). Out-of-range legacy values were clamped by M-VAVE. */",
       "#define FM6_NDX 128",
       "static const uint8_t FM6_DX[FM6_NDX][128] = {"]
for v in range(128):
    r = b[v * 128:(v + 1) * 128]
    name = "".join(chr(c) if 32 <= c < 127 else "?" for c in r[118:128]).strip()
    out.append("    /* %d %s */ {%s}," % (v, name.replace("*/", ""), ",".join(str(c) for c in r)))
out.append("};")
(root / "firmware" / "gen" / "lgs_fm6_dx.h").write_text("\n".join(out) + "\n")
print("wrote lgs_fm6_dx.h")
