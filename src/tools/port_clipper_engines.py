"""Mechanical port of Clipper's eng_digital.c and eng_drawbar.c into lgs_eng_fm2.h / lgs_eng_org.h (T2.1/T2.4).
The engines' own code is copied; only the glue changes (voice type, part / voice indexing, the engine descriptor).
Run from src/:  python3 tools/port_clipper_engines.py"""
import pathlib, re, sys
root = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(root / "tools"))
import famous_defs as D
src = root.parent / "clipper-smk" / "firmware" / "src"
out = root / "firmware" / "src"
HDR = """/* SPDX-License-Identifier: GPL-3.0-only
 * GENERATED by tools/port_clipper_engines.py from clipper-smk/firmware/src/%s - do not edit.
 * Engine code: Copyright (C) 2026 Leo Kuroshita (@kurogedelic), Hugelton Instruments (GPL-3.0). */
"""

def sub_ctl(s):
    return re.sub(r"\bCTL\b", "E32_CTL", s)       # the engines work on 32-sample windows (the core runs 16)

def cut_descriptor(s, name):
    i = s.index("static const engine_t " + name)
    j = s.index("\n};\n", i) + 4
    return s[:i] + s[j:]

# ---- DIGITAL -> FM2
s = (src / "eng_digital.c").read_text()
s = cut_descriptor(s, "ENG_DIGITAL")
FM2_EXTRA = '''    /* LiveGomezSynth's own variations: plucked strings */
    {"NYLON GTR", {4, 1, 1, 2, 35, 28, 8, 0}, {0, 72, 0, 50}, 0, 0, FX(0, 18, 20, 28)},
    {"STEEL GTR", {4, 1, 2, 3, 55, 32, 10, 0}, {0, 75, 0, 50}, 0, 0, FX(0, 22, 18, 26)},
    {"MUTED GTR", {4, 1, 1, 2, 45, 18, 6, 0}, {0, 50, 0, 25}, 0, 0, FX(0, 10, 10, 16)},
    {"JAZZ GTR", {4, 1, 1, 1, 28, 40, 0, 0}, {0, 80, 0, 60}, 0, 0, FX(0, 20, 16, 30)},
    /* the repertoire list (DOCs/notes/repertoire-coverage.md) */
    {"HARPSICHRD", {3, 1, 4, 6, 90, 20, 5, 0}, {0, 70, 0, 28}, 0, 0, FX(0, 8, 8, 26)},
    {"HARPSI BRT", {4, 2, 3, 5, 100, 16, 0, 0}, {0, 66, 0, 24}, 0, 0, FX(0, 6, 8, 24)},
    {"PAN FLUTE", {4, 1, 1, 1, 14, 60, 14, 0}, {18, 90, 127, 50}, 0, 0, FX(0, 0, 10, 40)},
    {"BELL PAD", {4, 5, 1, 8, 40, 95, 0, 0}, {55, 100, 127, 105}, 0, 0, FX(0, 40, 30, 66)},
    {"ATMOSPHERE", {4, 3, 1, 6, 55, 98, 6, 0}, {45, 100, 127, 110}, 0, 0, FX(0, 45, 25, 70)},
    {"BEAT STAB", {4, 8, 1, 4, 95, 30, 0, 0}, {0, 70, 0, 35}, 0, 0, FX(0, 10, 14, 16)},
    {"DIGITAL PNO", {4, 1, 2, 13, 70, 26, 12, 0}, {0, 84, 0, 55}, 0, 0, FX(0, 16, 10, 22)},
'''
FM2_EXTRA += D.rows(D.FM2)
i = s.index("DIGITAL_PRESETS[] = {")
j = s.index("\n};\n", i)
s = s[:j + 1] + FM2_EXTRA + s[j + 1:]
for old, new in (("DX RHODES", "FM TINE EP"), ("RHODES", "TINE EP"), ("M1 PIANO", "DIGI PIANO"), ("WURLI", "REED EP")):   # D-42: no trademarks
    s = s.replace('"%s"' % old, '"%s"' % new)
s = re.sub(r'static const char \*const N_FMALG\[\].*?;\n', "", s, flags=re.S)
s = re.sub(r'static const char \*const N_RATIO\[\].*?;\n', "", s, flags=re.S)
s = s.replace("voice_t", "cvoice_t")
s += '''
static const lgs_eng_t LGS_ENG_FM2 = {
    "FM2", OBV_FM2,
    {{"ALG", 0, 7}, {"R2", 0, 14}, {"R3", 0, 14}, {"R4", 0, 14}, {"IDX", 0, 127}, {"MDEC", 0, 127}, {"FB", 0, 127}, {"-", 0, 0}},
    DIGITAL_PRESETS, sizeof DIGITAL_PRESETS / sizeof DIGITAL_PRESETS[0],
    {4, 5, 6, 11}, digital_note_on, digital_render, 0,
};
'''
(out / "lgs_eng_fm2.h").write_text((HDR % "eng_digital.c") + sub_ctl(s))

# ---- DRAWBAR -> ORG
s = (src / "eng_drawbar.c").read_text()
s = cut_descriptor(s, "ENG_DRAWBAR")
ORG_EXTRA = '''    {"PURPLE DRV", {7, 0, 0, 0, 0, 50, 110, 2}, {0, 64, 127, 40}, 0, 0, FX(40, 0, 6, 20)},
    {"TONEWHEEL", {5, 0, 0, 2, 1, 70, 60, 2}, {0, 64, 127, 40}, 0, 0, FX(20, 0, 6, 22)},
    {"ROTARY BAL", {4, 0, 0, 0, 0, 20, 0, 1}, {10, 64, 127, 60}, 0, 0, FX(0, 10, 0, 40)},
    {"ACCORDION", {10, 0, 0, 0, 0, 10, 15, 0}, {6, 64, 127, 35}, 0, 0, FX(0, 30, 0, 24)},
'''
ORG_EXTRA += D.rows(D.ORG)
i = s.index("DRAWBAR_PRESETS[] = {")
j = s.index("\n};\n", i)
s = s[:j + 1] + ORG_EXTRA + s[j + 1:]
s = s.replace('"DIRTY B3"', '"DIRTY ORGAN"')
s = s.replace("voice_t", "cvoice_t")
s = s.replace("static drw_vc_t drw_v[NPART][NVOICE];", "static drw_vc_t drw_v[NPART][NVOICE];")
s = s.replace("static uint32_t drw_part(const track_t *t) { return (uint32_t)(t - trk) % NPART; }",
              "static uint32_t drw_part(const track_t *t) { (void)t; return lgs_cur_part; }")
s = s.replace("uint32_t vi = (uint32_t)(v - t->v) % NVOICE, k, held = 0;", "uint32_t vi = lgs_cur_vi, k, held;")
a = s.index("    for (k = 0; k < NVOICE; k++)                        /* single trigger")
b = s.index("    if (!V->init)")
s = s[:a] + "    held = (uint32_t)lgs_other_held(lgs_cur_part, vi);   /* single trigger: another key of the part held? */\n" + s[b:]
s = s.replace("drw_vc_t *V = &drw_v[drw_part(t)][(uint32_t)(v - t->v) % NVOICE];", "drw_vc_t *V = &drw_v[drw_part(t)][lgs_cur_vi];")
s += '''
static const lgs_eng_t LGS_ENG_ORG = {
    "ORG", OBV_ORG,
    {{"REG", 0, 15}, {"SUB", -8, 8}, {"BODY", -8, 8}, {"TOP", -8, 8}, {"PERC", 0, 6}, {"CLICK", 0, 127}, {"DRV", 0, 127}, {"ROTR", 0, 2}},
    DRAWBAR_PRESETS, sizeof DRAWBAR_PRESETS / sizeof DRAWBAR_PRESETS[0],
    {0, 4, 6, 7}, drawbar_note_on, drawbar_render, drawbar_block,
};
'''
(out / "lgs_eng_org.h").write_text((HDR % "eng_drawbar.c") + sub_ctl(s))
print("ported fm2 and org")

# ---- fm6_core.c (msfa) -> lgs_fm6_core.h, and the patch helpers of eng_fm6.c
s = (src / "fm6_core.c").read_text()
(out / "lgs_fm6_core.h").write_text((HDR % "fm6_core.c (Apache-2.0, see the file header)").replace("SPDX-License-Identifier: GPL-3.0-only", "SPDX-License-Identifier: Apache-2.0") + re.sub(r"\blive\b", "alive", sub_ctl(s)))   # (`live` is a macro of the voice core)
e = (src / "eng_fm6.c").read_text()
a = e.index("/* the highest value of each byte of the 155-byte voice */")
b = e.index("/* 155-byte voice -> 128-byte packed record")
(out / "lgs_fm6_patch.h").write_text((HDR % "eng_fm6.c") + e[a:b])
print("ported fm6 core and patch helpers")
